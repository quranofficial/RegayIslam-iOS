#!/usr/bin/env python3
"""Apply iOS bundle metadata, app icon, and notification sound resources."""
from pathlib import Path
import json
import plistlib
import re
import subprocess

plist_path = Path('ios/Runner/Info.plist')
if not plist_path.exists():
    raise SystemExit('ios/Runner/Info.plist was not generated by Flutter.')

with plist_path.open('rb') as f:
    data = plistlib.load(f)

data['CFBundleDisplayName'] = 'ڕێگای ئیسلام'
data['CFBundleName'] = 'RegayIslam'
data['CFBundleIdentifier'] = 'com.nwezhakanm.regayislam'
data['NSLocationWhenInUseUsageDescription'] = 'بۆ نیشاندانی کاتی نوێژ و ئاراستەی قیبلە، شوێنی ئێستات بەکاردەهێنین.'

with plist_path.open('wb') as f:
    plistlib.dump(data, f, sort_keys=False)

# Replace generated iOS launcher icons while retaining the template's supported sizes.
icon_source = Path('assets/images/app_icon.png')
icon_set = Path('ios/Runner/Assets.xcassets/AppIcon.appiconset')
icon_set.mkdir(parents=True, exist_ok=True)
if not icon_source.exists():
    raise SystemExit('assets/images/app_icon.png is missing.')
contents_path = icon_set / 'Contents.json'
if contents_path.exists():
    contents = json.loads(contents_path.read_text())
    generated = 0
    for image in contents.get('images', []):
        filename = image.get('filename')
        if not filename:
            continue
        dimensions = image.get('size', '1024x1024').split('x')
        scale = int(str(image.get('scale', '1x')).replace('x', ''))
        width = int(float(dimensions[0]) * scale)
        height = int(float(dimensions[1]) * scale)
        subprocess.run([
            'sips', '-s', 'format', 'png', '-z', str(height), str(width),
            str(icon_source), '--out', str(icon_set / filename)
        ], check=True, stdout=subprocess.DEVNULL)
        generated += 1
    if generated == 0:
        raise SystemExit('No icon image entries were found in AppIcon Contents.json.')
else:
    subprocess.run([
        'sips', '-s', 'format', 'png', '-z', '1024', '1024',
        str(icon_source), '--out', str(icon_set / 'AppIcon.png')
    ], check=True)
    contents_path.write_text(json.dumps({
        'images': [{
            'filename': 'AppIcon.png',
            'idiom': 'universal',
            'platform': 'ios',
            'size': '1024x1024'
        }],
        'info': {'author': 'xcode', 'version': 1}
    }, ensure_ascii=False, indent=2))

# Register the short custom notification sound in the iOS app bundle.
sound_path = Path('ios/Runner/adhan.caf')
if not sound_path.exists():
    raise SystemExit('The generated iOS Adhan sound ios/Runner/adhan.caf is missing.')

project_path = Path('ios/Runner.xcodeproj/project.pbxproj')
if not project_path.exists():
    raise SystemExit('Xcode project file was not generated.')

project = project_path.read_text()
if 'adhan.caf in Resources' not in project:
    build_id = 'DADA00000000000000000001'
    file_id = 'DADA00000000000000000002'
    build_entry = (
        f'        {build_id} /* adhan.caf in Resources */ = '
        f'{{isa = PBXBuildFile; fileRef = {file_id} /* adhan.caf */; }};\n'
    )
    file_entry = (
        f'        {file_id} /* adhan.caf */ = '
        '{isa = PBXFileReference; lastKnownFileType = file; path = adhan.caf; '
        'sourceTree = "<group>"; };\n'
    )
    project = project.replace(
        '/* Begin PBXBuildFile section */\n',
        '/* Begin PBXBuildFile section */\n' + build_entry, 1)
    project = project.replace(
        '/* Begin PBXFileReference section */\n',
        '/* Begin PBXFileReference section */\n' + file_entry, 1)

    runner_group = re.search(
        r'([A-F0-9]{24}) /\* Runner \*/ = \{\s*isa = PBXGroup;.*?children = \(.*?\);',
        project, re.S)
    if not runner_group:
        raise SystemExit('Could not find the Runner group in project.pbxproj.')
    group_text = runner_group.group(0)
    group_text = group_text.replace(
        'children = (',
        'children = (\n                ' + file_id + ' /* adhan.caf */,', 1)
    project = (project[:runner_group.start(0)] + group_text
               + project[runner_group.end(0):])

    resources_section = re.search(
        r'/\* Begin PBXResourcesBuildPhase section \*/(.*?)/\* End PBXResourcesBuildPhase section \*/',
        project, re.S)
    if not resources_section:
        raise SystemExit('Could not find PBXResourcesBuildPhase.')
    resources_text = resources_section.group(1)
    resources_phase = re.search(r'files = \((.*?)\);', resources_text, re.S)
    if not resources_phase:
        raise SystemExit('Could not find the iOS Resources file list.')
    resources_text = resources_text[:resources_phase.start(1)] + (
        '\n                ' + build_id + ' /* adhan.caf in Resources */,'
        + resources_text[resources_phase.start(1):])
    project = (project[:resources_section.start(1)] + resources_text
               + project[resources_section.end(1):])
    project_path.write_text(project)

export_options = {
    'method': 'app-store-connect',
    'destination': 'export',
    'signingStyle': 'manual',
    'teamID': 'REPLACE_WITH_TEAM_ID',
    'provisioningProfiles': {
        'com.nwezhakanm.regayislam': 'REPLACE_WITH_PROFILE_NAME'
    },
    'stripSwiftSymbols': True,
    'compileBitcode': False,
}
with Path('ios/ExportOptions.plist').open('wb') as f:
    plistlib.dump(export_options, f, sort_keys=False)
